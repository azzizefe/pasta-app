// Merges scripts/i18n/source.json (Turkish) with every <lang>.json next to it into src/i18n/phrases.ts.
// Reports ids that are missing a translation (they fall back to English, then Turkish, at runtime)
// and translations whose {placeholders} don't match the Turkish source.
// Usage: node scripts/i18n/build-phrases.js
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const read = (name) => JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
const source = read('source.json');

// English first (it is the fallback), then the rest in file-name order.
const langs = fs
  .readdirSync(dir)
  .filter((f) => /^[a-z]{2}\.json$/.test(f))
  .map((f) => f.slice(0, 2))
  .sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));
const data = Object.fromEntries(langs.map((l) => [l, read(`${l}.json`)]));

const missing = Object.fromEntries(langs.map((l) => [l, []]));
const placeholderErrors = [];
const placeholders = (s) => (s.match(/\{\w+\}/g) || []).sort().join();

const rows = Object.entries(source).map(([id, tr]) => {
  const want = placeholders(tr);
  const cells = langs.map((lang) => {
    const value = data[lang][id];
    if (!value) {
      missing[lang].push(id);
      return '';
    }
    if (placeholders(value) !== want) {
      placeholderErrors.push(`${lang} #${id}: expected ${want || 'none'}, got ${placeholders(value) || 'none'}`);
    }
    return value;
  });
  return [tr, ...cells];
});

const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
fs.writeFileSync(
  path.join(dir, '..', '..', 'src', 'i18n', 'phrases.ts'),
  `// Generated by scripts/i18n/build-phrases.js — edit scripts/i18n/*.json instead.\n` +
    `import type { SupportedLanguage } from './languages';\n\n` +
    `/** Column order after the Turkish source in each row. */\n` +
    `export const PHRASE_LANGUAGES: readonly SupportedLanguage[] = ${JSON.stringify(langs)};\n\n` +
    `/** Each row: [Turkish source, ...one translation per PHRASE_LANGUAGES entry]. */\n` +
    `export const PHRASES: ReadonlyArray<readonly string[]> = [\n${body}\n];\n`,
);

console.log(`${rows.length} phrases × ${langs.length} languages (${langs.join(', ')}) written to src/i18n/phrases.ts`);
for (const [lang, ids] of Object.entries(missing)) {
  if (ids.length) console.log(`missing ${lang}: ${ids.length} (${ids.slice(0, 15).join(', ')}${ids.length > 15 ? ', …' : ''})`);
}
if (placeholderErrors.length) {
  console.log('placeholder mismatches:\n  ' + placeholderErrors.join('\n  '));
  process.exitCode = 1;
}
